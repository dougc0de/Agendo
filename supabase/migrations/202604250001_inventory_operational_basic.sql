alter table public.inventory_items
    add column if not exists descripcion text null,
    add column if not exists tipo varchar(20) not null default 'desechable',
    add column if not exists scope_type varchar(20) not null default 'global',
    add column if not exists branch_id bigint null,
    add column if not exists controla_stock boolean not null default false,
    add column if not exists allow_negative_stock boolean not null default false,
    add column if not exists created_by_user_id bigint null,
    add column if not exists updated_by_user_id bigint null;

update public.inventory_items
set
    descripcion = coalesce(descripcion, null),
    tipo = coalesce(tipo, 'desechable'),
    scope_type = coalesce(scope_type, 'global'),
    branch_id = branch_id,
    controla_stock = coalesce(controla_stock, false),
    allow_negative_stock = coalesce(allow_negative_stock, false);

alter table public.inventory_items
    drop constraint if exists chk_inventory_items_tipo;

alter table public.inventory_items
    add constraint chk_inventory_items_tipo
    check (tipo in ('desechable', 'reusable'));

alter table public.inventory_items
    drop constraint if exists chk_inventory_items_scope_type;

alter table public.inventory_items
    add constraint chk_inventory_items_scope_type
    check (scope_type in ('global', 'sucursal'));

alter table public.inventory_items
    drop constraint if exists chk_inventory_items_scope_branch;

alter table public.inventory_items
    add constraint chk_inventory_items_scope_branch
    check (
        (scope_type = 'global' and branch_id is null)
        or (scope_type = 'sucursal' and branch_id is not null)
    );

