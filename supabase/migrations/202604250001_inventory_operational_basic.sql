create table if not exists public.inventory_stock_levels (
    id bigint generated by default as identity primary key,
    workspace_id bigint not null,
    inventory_item_id bigint not null,
    branch_id bigint not null,
    current_stock numeric(12, 2) not null default 0,
    minimum_stock numeric(12, 2) not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint uq_inventory_stock_levels_item_branch
        unique (inventory_item_id, branch_id),
    constraint fk_inventory_stock_levels_workspace_id_workspaces
        foreign key (workspace_id)
        references public.workspaces(id)
        on delete cascade,
    constraint fk_inventory_stock_levels_inventory_item_id_inventory_items
        foreign key (inventory_item_id)
        references public.inventory_items(id)
        on delete cascade,
    constraint fk_inventory_stock_levels_branch_id_sucursales
        foreign key (branch_id)
        references public.sucursales(id)
        on delete restrict,
    constraint chk_inventory_stock_levels_minimum_stock
        check (minimum_stock >= 0)
);

create index if not exists idx_inventory_stock_levels_workspace_id
    on public.inventory_stock_levels (workspace_id);

create index if not exists idx_inventory_stock_levels_branch_id
    on public.inventory_stock_levels (branch_id);

create index if not exists idx_inventory_stock_levels_inventory_item_id
    on public.inventory_stock_levels (inventory_item_id);

drop trigger if exists trg_inventory_stock_levels_updated_at on public.inventory_stock_levels;
create trigger trg_inventory_stock_levels_updated_at
before update on public.inventory_stock_levels
for each row
execute function public.set_updated_at();

create table if not exists public.inventory_movements (
    id bigint generated by default as identity primary key,
    workspace_id bigint not null,
    inventory_item_id bigint not null,
    stock_level_id bigint not null,
    branch_id bigint not null,
    reservation_id bigint null,
    charge_id bigint null,
    movement_type varchar(20) not null,
    origin_type varchar(30) not null,
    quantity numeric(12, 2) not null,
    quantity_delta numeric(12, 2) not null,
    stock_before numeric(12, 2) not null,
    stock_after numeric(12, 2) not null,
    unit_cost_reference numeric(12, 2) not null default 0,
    created_by_user_id bigint not null,
    observation text null,
    created_at timestamptz not null default now(),
    constraint fk_inventory_movements_workspace_id_workspaces
        foreign key (workspace_id)
        references public.workspaces(id)
        on delete cascade,
    constraint fk_inventory_movements_inventory_item_id_inventory_items
        foreign key (inventory_item_id)
        references public.inventory_items(id)
        on delete cascade,
    constraint fk_inventory_movements_stock_level_id_inventory_stock_levels
        foreign key (stock_level_id)
        references public.inventory_stock_levels(id)
        on delete cascade,
    constraint fk_inventory_movements_branch_id_sucursales
        foreign key (branch_id)
        references public.sucursales(id)
        on delete restrict,
    constraint fk_inventory_movements_reservation_id_reservas
        foreign key (reservation_id)
        references public.reservas(id)
        on delete set null,
    constraint fk_inventory_movements_charge_id_reservation_charges
        foreign key (charge_id)
        references public.reservation_charges(id)
        on delete set null,
    constraint fk_inventory_movements_created_by_user_id_usuarios
        foreign key (created_by_user_id)
        references public.usuarios(id)
        on delete restrict,
    constraint chk_inventory_movements_movement_type
        check (movement_type in ('entrada', 'salida', 'ajuste', 'consumo', 'devolucion')),
    constraint chk_inventory_movements_origin_type
        check (origin_type in ('manual', 'procedure_report', 'item_creation')),
    constraint chk_inventory_movements_quantity
        check (quantity > 0),
    constraint chk_inventory_movements_quantity_delta
        check (quantity_delta <> 0),
    constraint chk_inventory_movements_unit_cost_reference
        check (unit_cost_reference >= 0)
);

create index if not exists idx_inventory_movements_workspace_id
    on public.inventory_movements (workspace_id);

create index if not exists idx_inventory_movements_item_id
    on public.inventory_movements (inventory_item_id);

create index if not exists idx_inventory_movements_branch_id
    on public.inventory_movements (branch_id);

create index if not exists idx_inventory_movements_created_at
    on public.inventory_movements (created_at desc);

create index if not exists idx_inventory_movements_charge_id
    on public.inventory_movements (charge_id);

create index if not exists idx_inventory_movements_reservation_id
    on public.inventory_movements (reservation_id);
