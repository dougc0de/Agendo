create table if not exists public.kpi_daily_snapshots (
    id bigint generated by default as identity primary key,
    workspace_id bigint not null,
    metric_date date not null,
    grain_type varchar(30) not null,
    branch_id bigint null,
    room_id bigint null,
    doctor_user_id bigint null,
    procedure_name varchar(150) null,
    currency_code varchar(10) null,
    scheduled_count integer not null default 0,
    confirmed_count integer not null default 0,
    cancelled_count integer not null default 0,
    attended_count integer not null default 0,
    no_show_count integer not null default 0,
    booked_minutes integer not null default 0,
    operational_minutes integer not null default 0,
    idle_minutes integer not null default 0,
    paid_revenue numeric(12, 2) not null default 0,
    pending_revenue numeric(12, 2) not null default 0,
    exonerated_amount numeric(12, 2) not null default 0,
    supplies_cost numeric(12, 2) not null default 0,
    gross_margin_amount numeric(12, 2) not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint fk_kpi_daily_snapshots_workspace_id_workspaces
        foreign key (workspace_id)
        references public.workspaces(id)
        on delete cascade,
    constraint fk_kpi_daily_snapshots_branch_id_sucursales
        foreign key (branch_id)
        references public.sucursales(id)
        on delete set null,
    constraint fk_kpi_daily_snapshots_room_id_salas
        foreign key (room_id)
        references public.salas(id)
        on delete set null,
    constraint fk_kpi_daily_snapshots_doctor_user_id_usuarios
        foreign key (doctor_user_id)
        references public.usuarios(id)
        on delete set null,
    constraint chk_kpi_daily_snapshots_grain_type
        check (grain_type in ('workspace', 'branch', 'room', 'doctor', 'procedure'))
);

create index if not exists idx_kpi_daily_snapshots_workspace_date
