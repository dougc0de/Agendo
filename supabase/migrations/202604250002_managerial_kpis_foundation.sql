create or replace view public.vw_kpi_reservation_facts as
select
    r.workspace_id,
    r.id as reservation_id,
    r.fecha as reservation_date,
    r.created_at as reservation_created_at,
    r.updated_at as reservation_updated_at,
    r.estado as reservation_status,
    r.appointment_outcome,
    r.tipo_atencion,
    r.tipo_consulta,
    r.confirmed_at,
    r.confirmed_by_user_id,
    r.cancelled_at,
    r.cancelled_by_user_id,
    r.cancellation_reason,
    r.checked_in_at,
    r.completed_at,
    r.outcome_recorded_at,
    r.outcome_recorded_by_user_id,
    r.usuario_id as reservation_user_id,
    u.nombre as reservation_user_name,
    r.paciente_id,
    p.nombre as patient_name,
    r.sala_id as room_id,
    s.nombre as room_name,
    s.estado as room_status,
    s.sucursal_id as branch_id,
    su.nombre as branch_name,
    greatest(
        0,
        floor(extract(epoch from (r.hora_fin - r.hora_inicio)) / 60)
    )::int as duration_minutes,
    rc.id as charge_id,
    rc.payment_status,
    rc.payment_method,
    rc.paid_at,
    rc.currency_code,
    rc.charge_decision,
    rc.pricing_mode,
    coalesce(rc.room_charge_amount, 0) as room_charge_amount,
    coalesce(rc.supplies_total_amount, 0) as supplies_total_amount,
    coalesce(rc.supplies_total_cost, 0) as supplies_total_cost,
    coalesce(rc.total_billed_amount, rc.amount, 0) as total_billed_amount,
    case
        when rc.charge_decision = 'cobrable' and rc.payment_status = 'pagado'
            then coalesce(rc.total_billed_amount, rc.amount, 0)
        else 0
    end as paid_revenue,
    case
        when rc.charge_decision = 'cobrable' and rc.payment_status = 'pendiente'
            then coalesce(rc.total_billed_amount, rc.amount, 0)
        else 0
    end as pending_revenue,
    case
        when rc.charge_decision = 'exonerado'
            then coalesce(rc.total_billed_amount, rc.amount, 0)
        else 0
    end as exonerated_amount,
    case
        when rc.charge_decision = 'cobrable' and rc.payment_status = 'pagado'
            then coalesce(rc.total_billed_amount, rc.amount, 0) - coalesce(rc.supplies_total_cost, 0)
        else null
    end as gross_margin_amount
from public.reservas r
left join public.usuarios u
    on u.id = r.usuario_id
left join public.pacientes p
    on p.id = r.paciente_id
   and p.workspace_id = r.workspace_id
left join public.salas s
    on s.id = r.sala_id
   and s.workspace_id = r.workspace_id
left join public.sucursales su
    on su.id = s.sucursal_id
left join public.reservation_charges rc
    on rc.reservation_id = r.id
   and rc.workspace_id = r.workspace_id;
