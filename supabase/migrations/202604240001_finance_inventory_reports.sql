    add column if not exists waiver_reason text null;

update public.reservation_charges
set
    pricing_mode = coalesce(pricing_mode, 'solo_sala'),
    room_charge_amount = case
        when room_charge_amount > 0 then room_charge_amount
        else coalesce(amount, 0)
    end,
    supplies_total_amount = coalesce(supplies_total_amount, 0),
    supplies_total_cost = coalesce(supplies_total_cost, 0),
    total_billed_amount = case
        when total_billed_amount > 0 then total_billed_amount
        else coalesce(amount, 0)
    end,
    charge_decision = coalesce(charge_decision, 'cobrable');

