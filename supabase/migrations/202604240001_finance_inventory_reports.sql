create table if not exists public.inventory_items (
    id bigint generated by default as identity primary key,
    workspace_id bigint not null,
    nombre varchar(150) not null,
    categoria varchar(80),
    unidad varchar(40) not null default 'unidad',
    costo_base numeric(12, 2) not null default 0,
    precio_sugerido numeric(12, 2) not null default 0,
    estado varchar(20) not null default 'activo',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint fk_inventory_items_workspace_id_workspaces
        foreign key (workspace_id)
        references public.workspaces(id)
        on delete cascade,
    constraint chk_inventory_items_estado
        check (estado in ('activo', 'inactivo')),
    constraint chk_inventory_items_costo_base
        check (costo_base >= 0),
    constraint chk_inventory_items_precio_sugerido
        check (precio_sugerido >= 0)
);

create index if not exists idx_inventory_items_workspace_id
    on public.inventory_items (workspace_id);

create index if not exists idx_inventory_items_estado
    on public.inventory_items (estado);

drop trigger if exists trg_inventory_items_updated_at on public.inventory_items;
create trigger trg_inventory_items_updated_at
before update on public.inventory_items
for each row
execute function public.set_updated_at();

create table if not exists public.reservation_charge_supplies (
    id bigint generated by default as identity primary key,
    workspace_id bigint not null,
    charge_id bigint not null,
    inventory_item_id bigint null,
    item_name_snapshot varchar(150) not null,
    item_category_snapshot varchar(80),
    unit_snapshot varchar(40) not null default 'unidad',
    quantity numeric(12, 2) not null,
    unit_cost numeric(12, 2) not null default 0,
    unit_price numeric(12, 2) not null default 0,
    subtotal_cost numeric(12, 2) not null default 0,
    subtotal_price numeric(12, 2) not null default 0,
    notes text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint fk_reservation_charge_supplies_workspace_id_workspaces
        foreign key (workspace_id)
        references public.workspaces(id)
        on delete cascade,
    constraint fk_reservation_charge_supplies_charge_id_reservation_charges
        foreign key (charge_id)
        references public.reservation_charges(id)
        on delete cascade,
    constraint fk_reservation_charge_supplies_inventory_item_id_inventory_items
        foreign key (inventory_item_id)
        references public.inventory_items(id)
        on delete set null,
    constraint chk_reservation_charge_supplies_quantity
        check (quantity > 0),
    constraint chk_reservation_charge_supplies_unit_cost
        check (unit_cost >= 0),
    constraint chk_reservation_charge_supplies_unit_price
        check (unit_price >= 0),
    constraint chk_reservation_charge_supplies_subtotal_cost
        check (subtotal_cost >= 0),
    constraint chk_reservation_charge_supplies_subtotal_price
        check (subtotal_price >= 0)
);

create index if not exists idx_reservation_charge_supplies_workspace_id
    on public.reservation_charge_supplies (workspace_id);

create index if not exists idx_reservation_charge_supplies_charge_id
    on public.reservation_charge_supplies (charge_id);

