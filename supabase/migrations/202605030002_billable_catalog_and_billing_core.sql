    penalties_enabled,
    whatsapp_enabled
)
select
    w.id,
    true,
    case when coalesce(s.plan_code, 'basic') in ('premium', 'enterprise') then true else false end,
    true,
    case when coalesce(s.plan_code, 'basic') in ('premium', 'enterprise') then true else false end,
    case when coalesce(s.plan_code, 'basic') in ('premium', 'enterprise') then true else false end,
    false,
    false,
    case when coalesce(s.plan_code, 'basic') = 'enterprise' then true else false end,
    case when coalesce(s.plan_code, 'basic') = 'enterprise' then true else false end,
    case when coalesce(s.plan_code, 'basic') in ('premium', 'enterprise') then true else false end,
    case when coalesce(s.plan_code, 'basic') in ('premium', 'enterprise') then true else false end,
    false
