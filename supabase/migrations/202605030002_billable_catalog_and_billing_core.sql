create or replace view public.billing_document_financials as
with payment_agg as (
    select
        bdp.workspace_id,
        bdp.document_id,
        coalesce(sum(bdp.amount), 0)::numeric(12, 2) as paid_amount,
        count(*)::int as payment_count,
        max(bdp.paid_at) as last_payment_at
    from public.billing_document_payments bdp
    group by bdp.workspace_id, bdp.document_id
)
select
    bd.workspace_id,
    bd.id as document_id,
    bd.reservation_id,
    bd.currency_code,
    bd.document_status,
    bd.charge_decision,
    bd.total_amount::numeric(12, 2) as total_amount,
    coalesce(pa.paid_amount, 0)::numeric(12, 2) as paid_amount,
    greatest(
        bd.total_amount::numeric(12, 2) - coalesce(pa.paid_amount, 0)::numeric(12, 2),
        0::numeric
    )::numeric(12, 2) as outstanding_amount,
    coalesce(pa.payment_count, 0) as payment_count,
    pa.last_payment_at,
    case
        when bd.charge_decision = 'exonerado' then 'exonerado'
        when bd.document_status = 'anulado' then 'anulado'
        when greatest(
            bd.total_amount::numeric(12, 2) - coalesce(pa.paid_amount, 0)::numeric(12, 2),
            0::numeric
        ) = 0::numeric then 'pagado'
        when coalesce(pa.paid_amount, 0)::numeric(12, 2) > 0::numeric then 'parcial'
        else 'pendiente'
    end as financial_status
from public.billing_documents bd
left join payment_agg pa
    on pa.document_id = bd.id
   and pa.workspace_id = bd.workspace_id;
