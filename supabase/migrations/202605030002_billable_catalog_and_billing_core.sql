    workspace_id,
    finance_enabled,
    inventory_enabled,
    billable_catalog_enabled,
    manual_billing_enabled,
    partial_payments_enabled,
    packages_enabled,
    memberships_enabled,
    rentals_enabled,
    commissions_enabled,
