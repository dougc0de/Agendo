create table if not exists public.reservation_charges (
    id bigint generated by default as identity primary key,
    workspace_id bigint not null,
    reservation_id bigint not null,
    patient_id bigint not null,
    patient_name_snapshot varchar(150) not null,
    room_id bigint not null,
    room_name_snapshot varchar(150) not null,
    branch_id bigint null,
    branch_name_snapshot varchar(150),
    procedure_name varchar(150) not null,
    tipo_atencion varchar(30) not null,
    amount numeric(12, 2) not null,
    currency_code varchar(10) not null default 'CRC',
    payment_status varchar(30) not null default 'pendiente',
    payment_method varchar(30) not null default 'otro',
    paid_at timestamptz null,
    registered_by_user_id bigint not null,
    notes text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint uq_reservation_charges_reservation_id unique (reservation_id),
    constraint fk_reservation_charges_workspace_id_workspaces
        foreign key (workspace_id)
        references public.workspaces(id)
        on delete cascade,
    constraint fk_reservation_charges_reservation_id_reservas
        foreign key (reservation_id)
        references public.reservas(id)
        on delete cascade,
    constraint fk_reservation_charges_patient_id_pacientes
        foreign key (patient_id)
        references public.pacientes(id)
        on delete restrict,
    constraint fk_reservation_charges_room_id_salas
        foreign key (room_id)
        references public.salas(id)
        on delete restrict,
    constraint fk_reservation_charges_branch_id_sucursales
        foreign key (branch_id)
        references public.sucursales(id)
        on delete set null,
    constraint fk_reservation_charges_registered_by_user_id_usuarios
        foreign key (registered_by_user_id)
        references public.usuarios(id)
        on delete restrict,
    constraint chk_reservation_charges_tipo_atencion
        check (tipo_atencion in ('consulta', 'procedimiento')),
    constraint chk_reservation_charges_payment_status
        check (payment_status in ('pendiente', 'pagado', 'anulado')),
    constraint chk_reservation_charges_payment_method
        check (payment_method in ('efectivo', 'tarjeta', 'transferencia', 'otro')),
    constraint chk_reservation_charges_amount
        check (amount >= 0)
);

create index if not exists idx_reservation_charges_workspace_id
    on public.reservation_charges (workspace_id);

create index if not exists idx_reservation_charges_payment_status
