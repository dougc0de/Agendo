alter table public.workspace_settings
    add column if not exists consultation_open_time time not null default '08:00:00',
    add column if not exists consultation_close_time time null default '17:00:00',
    add column if not exists consultation_no_closing boolean not null default false,
    add column if not exists procedure_open_time time not null default '08:00:00',
    add column if not exists procedure_close_time time null default '17:00:00',
    add column if not exists procedure_no_closing boolean not null default false,
    add column if not exists time_zone varchar(80) not null default 'America/Costa_Rica';

update public.workspace_settings ws
set
    consultation_open_time = coalesce(c.hora_apertura, ws.consultation_open_time),
    consultation_close_time = coalesce(c.hora_cierre, ws.consultation_close_time),
    procedure_open_time = coalesce(c.hora_apertura, ws.procedure_open_time),
    procedure_close_time = coalesce(c.hora_cierre, ws.procedure_close_time)
from public.clinicas c
where c.workspace_id = ws.workspace_id;

alter table public.workspace_settings
    drop constraint if exists chk_workspace_settings_consultation_hours;

alter table public.workspace_settings
    add constraint chk_workspace_settings_consultation_hours
    check (
        (
            consultation_no_closing = true
            and consultation_open_time is not null
        )
        or (
            consultation_no_closing = false
            and consultation_open_time is not null
            and consultation_close_time is not null
            and consultation_close_time > consultation_open_time
        )
    );

alter table public.workspace_settings
    drop constraint if exists chk_workspace_settings_procedure_hours;

alter table public.workspace_settings
    add constraint chk_workspace_settings_procedure_hours
    check (
        (
            procedure_no_closing = true
            and procedure_open_time is not null
        )
        or (
            procedure_no_closing = false
            and procedure_open_time is not null
            and procedure_close_time is not null
            and procedure_close_time > procedure_open_time
        )
    );

alter table public.reservas
    add column if not exists tipo_atencion varchar(30);

update public.reservas
set tipo_atencion = case
    when lower(coalesce(tipo_consulta, '')) like '%cirug%' then 'procedimiento'
    when lower(coalesce(tipo_consulta, '')) like '%quirur%' then 'procedimiento'
    when lower(coalesce(tipo_consulta, '')) like '%proced%' then 'procedimiento'
    when lower(coalesce(tipo_consulta, '')) like '%laparo%' then 'procedimiento'
    when lower(coalesce(tipo_consulta, '')) like '%endosc%' then 'procedimiento'
    when lower(coalesce(tipo_consulta, '')) like '%biops%' then 'procedimiento'
    when lower(coalesce(tipo_consulta, '')) like '%interven%' then 'procedimiento'
    else 'consulta'
end
where tipo_atencion is null;

