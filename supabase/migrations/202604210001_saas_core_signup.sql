create table if not exists public.workspaces (
    id bigint generated by default as identity primary key,
    nombre varchar(120) not null,
    slug varchar(160) not null,
    estado varchar(50) not null default 'activo',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint uq_workspaces_slug unique (slug),
    constraint chk_workspaces_estado
        check (estado in ('activo', 'suspendido', 'cancelado'))
);

create index if not exists idx_workspaces_estado on public.workspaces (estado);

create table if not exists public.workspace_members (
    id bigint generated by default as identity primary key,
    workspace_id bigint not null,
    usuario_id bigint not null,
    role varchar(50) not null,
    estado varchar(50) not null default 'activo',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint fk_workspace_members_workspace_id_workspaces
        foreign key (workspace_id)
        references public.workspaces(id)
        on delete cascade
        on update no action,
    constraint fk_workspace_members_usuario_id_usuarios
        foreign key (usuario_id)
        references public.usuarios(id)
        on delete cascade
        on update no action,
    constraint uq_workspace_members_workspace_usuario unique (workspace_id, usuario_id),
    constraint chk_workspace_members_role
        check (role in ('owner', 'admin', 'staff')),
    constraint chk_workspace_members_estado
        check (estado in ('activo', 'invitado', 'suspendido'))
);

create index if not exists idx_workspace_members_workspace_id
    on public.workspace_members (workspace_id);
create index if not exists idx_workspace_members_usuario_id
    on public.workspace_members (usuario_id);

create table if not exists public.subscriptions (
    id bigint generated by default as identity primary key,
    workspace_id bigint not null,
    plan_code varchar(50) not null,
    commercial_status varchar(50) not null,
    billing_mode varchar(50) not null default 'paid',
    trial_ends_at timestamptz,
    current_period_ends_at timestamptz,
    max_users integer not null,
    max_rooms integer not null,
    max_reservations_per_month integer not null,
    partner_valid_until timestamptz,
    partner_notes varchar(255),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint uq_subscriptions_workspace_id unique (workspace_id),
    constraint fk_subscriptions_workspace_id_workspaces
        foreign key (workspace_id)
        references public.workspaces(id)
        on delete cascade
        on update no action,
    constraint chk_subscriptions_plan_code
        check (plan_code in ('basic', 'premium', 'enterprise')),
    constraint chk_subscriptions_commercial_status
        check (
            commercial_status in (
                'trial',
                'active',
                'partner_comped',
                'past_due',
                'canceled',
                'suspended'
            )
        ),
    constraint chk_subscriptions_billing_mode
        check (billing_mode in ('paid', 'comped')),
    constraint chk_subscriptions_limits
        check (
            max_users >= 1 and
            max_rooms >= 1 and
            max_reservations_per_month >= 1
        )
);

create index if not exists idx_subscriptions_plan_code on public.subscriptions (plan_code);
create index if not exists idx_subscriptions_commercial_status
    on public.subscriptions (commercial_status);

