insert into public.workspace_members (workspace_id, usuario_id, role, estado)
select
    w.id,
    u.id,
    'owner',
    'activo'
from public.workspaces w
cross join public.usuarios u
where (
      w.slug = 'agendo-legacy'
      or w.slug like 'legacy-clinic-%'
  )
  and not exists (
      select 1
      from public.workspace_members wm
      where wm.workspace_id = w.id
        and wm.usuario_id = u.id
  );

insert into public.subscriptions (
    workspace_id,
    plan_code,
    commercial_status,
    billing_mode,
    trial_ends_at,
    current_period_ends_at,
    max_users,
    max_rooms,
    max_reservations_per_month
)
select
    w.id,
    'basic',
    'active',
    'paid',
    null,
    now() + interval '30 days',
    3,
    3,
    500
from public.workspaces w
where (
      w.slug = 'agendo-legacy'
      or w.slug like 'legacy-clinic-%'
  )
  and not exists (
      select 1
      from public.subscriptions s
      where s.workspace_id = w.id
  );

